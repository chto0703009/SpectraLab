function testDifferentWavelengthRangesAreAllowed(testCase)

    referenceSpec = spectralab.core.Spectrum( ...
        [380; 390; 400], ...
        [1.0; 2.0; 1.5]);

    sampleSpec = spectralab.core.Spectrum( ...
        [390; 400; 410; 420], ...
        [0.8; 1.2; 1.0; 0.7]);

    [referenceResult, sampleResult] = ...
        spectralab.core.resampleSpectrumPair( ...
            referenceSpec, ...
            sampleSpec, ...
            RefinementFactor=2);

    verifyEqual(testCase, referenceResult.WavelengthNm(1), 380);
    verifyEqual(testCase, referenceResult.WavelengthNm(end), 400);

    verifyEqual(testCase, sampleResult.WavelengthNm(1), 390);
    verifyEqual(testCase, sampleResult.WavelengthNm(end), 420);

end


function testDefaultMatchesExplicitSettings(testCase)

    referenceSpec = createReferenceSpectrum();
    sampleSpec = createSampleSpectrum();

    [defaultReference, defaultSample] = ...
        spectralab.core.resampleSpectrumPair( ...
            referenceSpec, ...
            sampleSpec);

    [explicitReference, explicitSample] = ...
        spectralab.core.resampleSpectrumPair( ...
            referenceSpec, ...
            sampleSpec, ...
            RefinementFactor=4, ...
            Method="pchip");

    verifyEqual( ...
        testCase, ...
        defaultReference.WavelengthNm, ...
        explicitReference.WavelengthNm);

    verifyEqual( ...
        testCase, ...
        defaultReference.Power, ...
        explicitReference.Power, ...
        "AbsTol", 1e-12);

    verifyEqual( ...
        testCase, ...
        defaultSample.WavelengthNm, ...
        explicitSample.WavelengthNm);

    verifyEqual( ...
        testCase, ...
        defaultSample.Power, ...
        explicitSample.Power, ...
        "AbsTol", 1e-12);

end


function referenceSpec = createReferenceSpectrum()

    referenceSpec = spectralab.core.Spectrum( ...
        [380; 390; 400], ...
        [1.0; 2.0; 1.5]);

end


function sampleSpec = createSampleSpectrum()

    sampleSpec = spectralab.core.Spectrum( ...
        [385; 395; 405], ...
        [0.5; 1.0; 0.6]);

end