function testReturnsTwoRefinedSpectra(testCase)

    referenceSpec = createReferenceSpectrum();
    sampleSpec = createSampleSpectrum();

    [referenceResult, sampleResult] = ...
        spectralab.core.resampleSpectrumPair( ...
            referenceSpec, ...
            sampleSpec, ...
            RefinementFactor=4);

    verifyEqual( ...
        testCase, ...
        referenceResult.WavelengthNm, ...
        (380:2.5:400).', ...
        "AbsTol", 1e-12);

    verifyEqual( ...
        testCase, ...
        sampleResult.WavelengthNm, ...
        (385:2.5:405).', ...
        "AbsTol", 1e-12);

end


function testUsesSameInterpolationSettings(testCase)

    referenceSpec = createReferenceSpectrum();
    sampleSpec = createSampleSpectrum();

    [referenceResult, sampleResult] = ...
        spectralab.core.resampleSpectrumPair( ...
            referenceSpec, ...
            sampleSpec, ...
            RefinementFactor=2, ...
            Method="pchip");

    expectedReference = spectralab.core.resampleSpectrum( ...
        referenceSpec, ...
        RefinementFactor=2, ...
        Method="pchip");

    expectedSample = spectralab.core.resampleSpectrum( ...
        sampleSpec, ...
        RefinementFactor=2, ...
        Method="pchip");

    verifyEqual( ...
        testCase, ...
        referenceResult.WavelengthNm, ...
        expectedReference.WavelengthNm);

    verifyEqual( ...
        testCase, ...
        referenceResult.Power, ...
        expectedReference.Power, ...
        "AbsTol", 1e-12);

    verifyEqual( ...
        testCase, ...
        sampleResult.WavelengthNm, ...
        expectedSample.WavelengthNm);

    verifyEqual( ...
        testCase, ...
        sampleResult.Power, ...
        expectedSample.Power, ...
        "AbsTol", 1e-12);

end


