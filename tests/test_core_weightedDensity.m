	    verifyFalse(testCase, result.Resampled);
	    verifyEqual(testCase, result.RefinementFactor, 4);
	    verifyEqual(testCase, result.InterpolationMethod, "pchip");

	end


	function testFactorOneDoesNotAlterDensity(testCase)

	    reference = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [1.0; 2.0; 1.0]);

	    sample = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [0.5; 1.0; 0.5]);

	    weighting = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [1.0; 1.0; 1.0]);

	    normalResult = spectralab.core.weightedDensity( ...
	        reference, ...
	        sample, ...
	        weighting);

	    factorOneResult = spectralab.core.weightedDensity( ...
	        reference, ...
	        sample, ...
	        weighting, ...
	        Resample=true, ...
	        RefinementFactor=1);

	    verifyEqual( ...
	        testCase, ...
	        factorOneResult.Density, ...
	        normalResult.Density, ...
	        "AbsTol", 1e-12);

	    verifyEqual( ...
	        testCase, ...
	        factorOneResult.Transmittance, ...
	        normalResult.Transmittance, ...
	        "AbsTol", 1e-12);

	end


	function testResamplingSupportsDifferentGrids(testCase)

	    reference = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [1.0; 2.0; 1.0]);

	    sample = struct( ...
	        "WavelengthNm", [420; 480; 540; 600], ...
	        "Value", [0.5; 0.8; 0.7; 0.5]);

	    weighting = struct( ...
	        "WavelengthNm", [400; 450; 500; 550; 600], ...
	        "Value", [0.0; 0.5; 1.0; 0.5; 0.0]);

	    result = spectralab.core.weightedDensity( ...
	        reference, ...
	        sample, ...
	        weighting, ...
	        Resample=true, ...
	        RefinementFactor=4);

	    verifyTrue(testCase, isfinite(result.Density));
	    verifyTrue(testCase, isfinite(result.Transmittance));

	    verifyEqual( ...
	        testCase, ...
	        result.WavelengthRangeNm, ...
	        [420, 600]);

	end