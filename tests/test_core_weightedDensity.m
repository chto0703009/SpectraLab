function testNoCommonRangeThrowsError(testCase)

    reference = localSpectrum( ...
        [400; 500], ...
        [1; 1]);

    sample = localSpectrum( ...
        [600; 700], ...
        [0.5; 0.5]);

    weighting = localSpectrum( ...
        [400; 700], ...
        [1; 1]);

    verifyError(testCase, ...
        @() spectralab.core.weightedDensity( ...
            reference, ...
            sample, ...
            weighting), ...
        "spectralab:core:weightedDensity:NoOverlap");
end


