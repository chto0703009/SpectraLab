end
	
	
	function testResamplingCanBeEnabled(testCase)

	    reference = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [1.0; 2.0; 1.0]);

	    sample = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [0.5; 1.0; 0.5]);

	    weighting = struct( ...
	        "WavelengthNm", [400; 500; 600], ...
	        "Value", [1.0; 1.0; 1.0]);

	    result = spectralab.core.weightedDensity( ...
	        reference, ...
	        sample, ...
	        weighting, ...
	        Resample=true, ...
	        RefinementFactor=4, ...
	        InterpolationMethod="pchip");

	    verifyTrue(testCase, result.Resampled);
	    verifyEqual(testCase, result.RefinementFactor, 4);
	    verifyEqual(testCase, result.InterpolationMethod, "pchip");

	    verifyEqual( ...
	        testCase, ...
	        result.Transmittance, ...
	        0.5, ...
	        "AbsTol", 1e-12);

	    verifyEqual( ...
	        testCase, ...
	        result.Density, ...
	        -log10(0.5), ...
	        "AbsTol", 1e-12);

	end


	function testResamplingIsDisabledByDefault(testCase)

