function tests = test_core_weightedDensity
%TEST_CORE_WEIGHTEDDENSITY Tests for the shared weighted-density engine.

    tests = functiontests(localfunctions);
end


function testIdenticalSignalsGiveZeroDensity(testCase)

    wavelengthNm = (400:10:700).';

    reference = localSpectrum( ...
        wavelengthNm, ...
        ones(size(wavelengthNm)));

    sample = localSpectrum( ...
        wavelengthNm, ...
        ones(size(wavelengthNm)));

    weighting = localSpectrum( ...
        wavelengthNm, ...
        ones(size(wavelengthNm)));

    result = spectralab.core.weightedDensity( ...
        reference, ...
        sample, ...
        weighting);

    verifyEqual(testCase, result.Transmittance, 1, ...
        AbsTol=1e-12);

    verifyEqual(testCase, result.Density, 0, ...
        AbsTol=1e-12);
end


