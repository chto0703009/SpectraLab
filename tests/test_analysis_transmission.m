function testDifferentGridsAreAlignedWhenResamplingEnabled(testCase)

    referenceWavelength = (400:10:700).';
    sampleWavelength = (405:10:695).';

    referenceValue = ones(size(referenceWavelength));
    sampleValue = 0.5 .* ones(size(sampleWavelength));

    referenceArchive = makeArchive( ...
        referenceWavelength, ...
        referenceValue, ...
        "Reference");

    sampleArchive = makeArchive( ...
        sampleWavelength, ...
        sampleValue, ...
        "Sample");

    result = spectralab.analysis.transmission( ...
        referenceArchive, ...
        sampleArchive, ...
        Resample=true, ...
        RefinementFactor=2, ...
        WarnAboveOne=false);

    verifyGreaterThanOrEqual( ...
        testCase, ...
        result.Result.WavelengthNm(1), ...
        405);

    verifyLessThanOrEqual( ...
        testCase, ...
        result.Result.WavelengthNm(end), ...
        695);

    verifyEqual( ...
        testCase, ...
        result.Result.Value, ...
        0.5 .* ones(size(result.Result.Value)), ...
        AbsTol=1e-12);

    verifyEqual( ...
        testCase, ...
        result.Parameters.Alignment, ...
        "Interpolated");

    verifyTrue( ...
        testCase, ...
        result.Parameters.Resampled);
end


