        "TransmissionSpectrum");

    verifyEqual( ...
        testCase, ...
        result.Definition.Method, ...
        "SampleReferenceRatio");

    verifyEqual( ...
        testCase, ...
        result.Parameters.Alignment, ...
        "Interpolated");

    verifyTrue( ...
        testCase, ...
        result.Parameters.Resampled);

    verifyEqual( ...
        testCase, ...
        result.Parameters.RefinementFactor, ...
        4);

    verifyEqual( ...
        testCase, ...
        result.Parameters.InterpolationMethod, ...
        "makima");

    verifyEqual( ...
        testCase, ...
        result.Parameters.EffectiveWavelengthRangeNm, ...
        [400, 700]);

    verifyNotEmpty( ...
        testCase, ...
        result.Identity.ContentHash);
end


	function archive = makeArchive(wavelength, value, measurementName)
	%MAKEARCHIVE Create a minimal valid SpectraLab archive for testing.

	    archive = struct();


	    %% Identity

	    archive.Identity = struct();

	    archive.Identity.UUID = ...
	        string(java.util.UUID.randomUUID);

	    archive.Identity.Created = ...
	        datetime("now", "TimeZone", "UTC");

	    archive.Identity.CreatedBy = ...
	        "SpectraLab test";

	    archive.Identity.HashAlgorithm = ...
	        "SHA-256";

	    archive.Identity.ContentHash = ...
	        "";


	    %% Version

	    archive.Version = struct();

	    archive.Version.Format = ...
	        "SLAB-MAT";

	    archive.Version.Version = ...
	        "0.6";

	    archive.Version.Software = ...
	        spectralab.version();


	    %% Measurement

	    archive.Measurement = struct();

	    archive.Measurement.Name = ...
	        string(measurementName);

	    archive.Measurement.Timestamp = ...
	        datetime("now", "TimeZone", "UTC");

	    archive.Measurement.Wavelength = ...
	        double(wavelength(:));

	    archive.Measurement.Value = ...
	        double(value(:));

	    archive.Measurement.Mode = ...
	        "Emission";

	    archive.Measurement.Operator = ...
	        "SpectraLab test";


	    %% Metadata

	    archive.Metadata = struct();


	    %% Instrument

	    archive.Instrument = struct();

	    archive.Instrument.Name = ...
	        "Synthetic test instrument";

	    archive.Instrument.SerialNumber = ...
	        "TEST-001";


	    %% Quality

	    archive.Quality = struct();


	    %% History

	    archive.History = struct.empty;


	    %% Calculate the canonical archive content hash

	    payload = struct();

	    payload.Measurement = ...
	        archive.Measurement;

	    payload.Instrument = ...
	        archive.Instrument;

	    payload.Quality = ...
	        archive.Quality;

	    archive.Identity.ContentHash = ...
	        spectralab.archive.contentHash(payload);
	end