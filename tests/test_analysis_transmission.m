function tests = test_analysis_transmission
%TEST_ANALYSIS_TRANSMISSION Tests for spectralab.analysis.transmission.

    tests = functiontests(localfunctions);
end


function testIdenticalGridsWithoutResamplingUseMeasuredValues(testCase)

    wavelength = (400:10:700).';

    referenceValue = ones(size(wavelength));
    sampleValue = 0.5 .* ones(size(wavelength));

    referenceArchive = makeArchive( ...
        wavelength, ...
        referenceValue, ...
        "Reference");

    sampleArchive = makeArchive( ...
        wavelength, ...
        sampleValue, ...
        "Sample");

    result = spectralab.analysis.transmission( ...
        referenceArchive, ...
        sampleArchive, ...
        Resample=false, ...
        WarnAboveOne=false);

    verifyEqual( ...
        testCase, ...
        result.Result.WavelengthNm, ...
        wavelength);

    verifyEqual( ...
        testCase, ...
        result.Result.Value, ...
        0.5 .* ones(size(wavelength)), ...
        AbsTol=1e-12);

    verifyEqual( ...
        testCase, ...
        result.Parameters.Alignment, ...
        "Exact");

    verifyFalse( ...
        testCase, ...
        result.Parameters.Resampled);
end


function testIdenticalGridsAreRefinedWhenResamplingEnabled(testCase)

    wavelength = (400:10:700).';

    referenceValue = ones(size(wavelength));
    sampleValue = 0.5 .* ones(size(wavelength));

    referenceArchive = makeArchive( ...
        wavelength, ...
        referenceValue, ...
        "Reference");

    sampleArchive = makeArchive( ...
        wavelength, ...
        sampleValue, ...
        "Sample");

    result = spectralab.analysis.transmission( ...
        referenceArchive, ...
        sampleArchive, ...
        Resample=true, ...
        RefinementFactor=2, ...
        InterpolationMethod="pchip", ...
        WarnAboveOne=false);

    expectedSampleCount = ...
        (numel(wavelength) - 1) * 2 + 1;

    verifyEqual( ...
        testCase, ...
        numel(result.Result.WavelengthNm), ...
        expectedSampleCount);

    verifyEqual( ...
        testCase, ...
        result.Result.WavelengthNm(1), ...
        wavelength(1));

    verifyEqual( ...
        testCase, ...
        result.Result.WavelengthNm(end), ...
        wavelength(end));

    verifyEqual( ...
        testCase, ...
        result.Result.Value, ...
        0.5 .* ones(expectedSampleCount, 1), ...
        AbsTol=1e-12);

    verifyEqual( ...
        testCase, ...
        result.Parameters.Alignment, ...
        "Interpolated");

    verifyTrue( ...
        testCase, ...
        result.Parameters.Resampled);

    verifyEqual( ...
        testCase, ...
        result.Parameters.RefinementFactor, ...
        2);

    verifyEqual( ...
        testCase, ...
        result.Parameters.InterpolationMethod, ...
        "pchip");
end


