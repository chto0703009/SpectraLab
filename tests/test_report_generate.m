function tests = test_report_generate
%TEST_REPORT_GENERATE Verify RP-019 public report orchestration.

tests = functiontests(localfunctions);
end

function setup(testCase)

folder = string(tempname);
mkdir(folder);

testCase.TestData.TempFolder = folder;
testCase.addTeardown(@() removeFolder(folder));
end

function testGeneratesPdfFromSavedArchive(testCase)

folder = string(testCase.TestData.TempFolder);
archiveFile = fullfile(folder, "measurement.mat");
outputFolder = fullfile(folder, "reports");

archive = createArchiveFile(archiveFile);

specification = makeSpecification();

info = spectralab.report.generate( ...
    archiveFile, ...
    specification, ...
    outputFolder, ...
    GenerationTime=datetime(2026,7,30,10,0,0));

verifyTrue(testCase, isfile(info.PDFFile));
verifyEqual(testCase, ...
    string(info.PDFFile), ...
    fullfile(outputFolder, "measurement_ANL-TEST_report.pdf"));
verifyEqual(testCase, info.Context.Archive.UUID, archive.Identity.UUID);
verifyEqual(testCase, info.Context.Result.Value, 2.5);
verifyEqual(testCase, info.Context.Analysis.AnalysisId, "ANL-TEST");
verifyFalse(testCase, info.Context.Analysis.HasFigure);
end

