function testGeneratesPdfAndPngForFigureAnalysis(testCase)

folder = string(testCase.TestData.TempFolder);
archiveFile = fullfile(folder, "figure_measurement.mat");
outputFolder = fullfile(folder, "reports");

archive = createArchiveFile(archiveFile);

specification = makeSpecification();
specification.AnalysisDefinition.HasFigure = true;
specification.AnalysisDefinition.FigureDefinition = makeFigureDefinition();
specification.FigureRenderer = @renderFigure;

info = spectralab.report.generate( ...
    archiveFile, specification, outputFolder);

verifyTrue(testCase, isfile(info.PDFFile));
verifyTrue(testCase, isfile(info.PNGFile));
verifyEqual(testCase, ...
    string(info.PNGFile), ...
    fullfile(outputFolder, "figure_measurement_ANL-TEST_figure.png"));
verifyEqual(testCase, info.Context.Archive.UUID, archive.Identity.UUID);
end

function renderFigure(ax, archive, result)

plot(ax, ...
    archive.Measurement.Wavelength, ...
    archive.Measurement.Value, ...
    "LineWidth", 1.2);

grid(ax, "on");
xlabel(ax, "Wavelength (nm)");
ylabel(ax, "Relative value");
title(ax, "RP-019 generated figure");

if result.Value <= 0
    error("SpectraLab:Report:InvalidTestResult", ...
        "Test result must be positive.");
end
end

function definition = makeFigureDefinition()

definition = struct( ...
    "AspectRatio", 3/2, ...
    "WidthFraction", 0.82, ...
    "MaxHeight", 260, ...
    "Caption", "Measured spectrum generated by RP-019.");
end

function specification = makeSpecification()

definition = struct( ...
    "AnalysisId", "ANL-TEST", ...
    "Name", "Test Analysis", ...
    "Method", "Deterministic test method", ...
    "Standard", "SpectraLab test contract", ...
    "DefinitionVersion", "1", ...
    "HasFigure", false, ...
    "ResultFields", resultField());

specification = struct( ...
    "AnalysisDefinition", definition, ...
    "AnalysisRunner", @runAnalysis);
end

function specification = makeTwoArchiveSpecification()

definition = struct( ...
    "AnalysisId", "ANL-TWO-ARCHIVE", ...
    "Name", "Two Archive Contract", ...
    "Method", "Sample/reference mean ratio", ...
    "Standard", "SpectraLab test contract", ...
    "DefinitionVersion", "1", ...
    "HasFigure", false, ...
    "ResultFields", struct( ...
        "Field", "MeanRatio", ...
        "Label", "Mean ratio", ...
        "Unit", "", ...
        "Format", "%.3f"));

specification = struct( ...
    "InputRoles", ["Reference", "Sample"], ...
    "AnalysisDefinition", definition, ...
    "AnalysisRunner", @runTwoArchiveAnalysis);
end

function result = runTwoArchiveAnalysis(reference, sample)

ratio = double(sample.Measurement.Value) ./ ...
    double(reference.Measurement.Value);

result = struct("MeanRatio", mean(ratio));
end

function result = runAnalysis(archive)

result = struct( ...
    "Value", mean(double(archive.Measurement.Value)));
end

function field = resultField()

field = struct( ...
    "Field", "Value", ...
    "Label", "Value", ...
    "Unit", "a.u.", ...
    "Format", "%.2f");
end

function archive = createArchiveFile(archiveFile)

wavelength = (380:10:410).';
power = [1; 2; 3; 4];

instrument = struct( ...
    "Name", "X-Rite i1Pro 2", ...
    "Driver", "spotread", ...
    "SerialNumber", "1001799");

calibration = struct( ...
    "CalibrationID", "CAL-001");

metadata = struct( ...
    "Operator", "Christer Törnkvist", ...
    "Project", "RP-019", ...
    "SampleID", "PUBLIC-REPORT-001", ...
    "Description", "", ...
    "Laboratory", "", ...
    "Tags", strings(0), ...
    "Comment", "");

spec = spectralab.core.Spectrum( ...
    wavelength, ...
    power, ...
    "RP-019 measurement", ...
    instrument, ...
    calibration, ...
    metadata, ...
    "relative");

spec = spec.withTimestamp(datetime(2026,7,30,9,30,0));

archive = spectralab.archive.create(spec);
spectralab.archive.save(archive, archiveFile);
end

function removeFolder(folder)

if isfolder(folder)
    rmdir(folder, "s");
end
end

function archive = createCriArchiveFile(archiveFile)

wavelength = (380:10:730).';
power = 0.2 + ...
    0.6 * exp(-0.5 * ((wavelength - 455) / 25).^2) + ...
    0.9 * exp(-0.5 * ((wavelength - 545) / 45).^2) + ...
    0.5 * exp(-0.5 * ((wavelength - 610) / 35).^2);

instrument = struct( ...
    "Name", "X-Rite i1Pro 2", ...
    "Driver", "spotread", ...
    "SerialNumber", "1001799");

metadata = struct( ...
    "Operator", "Christer Törnkvist", ...
    "Project", "RP-020", ...
    "SampleID", "CRI-PUBLIC-001");

spec = spectralab.core.Spectrum( ...
    wavelength, ...
    power, ...
    "CRI public report", ...
    instrument, ...
    struct(), ...
    metadata, ...
    "relative");

archive = spectralab.archive.create(spec);
spectralab.archive.save(archive, archiveFile);
end

