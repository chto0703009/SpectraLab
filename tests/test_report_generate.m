function archive = createArchiveFile(archiveFile)

wavelength = (380:10:410).';
power = [1; 2; 3; 4];

instrument = struct( ...
    "Name", "X-Rite i1Pro 2", ...
    "Driver", "spotread", ...
    "SerialNumber", "1001799");

calibration = struct( ...
    "CalibrationID", "CAL-001");

metadata = struct( ...
    "Operator", "Christer Törnkvist", ...
    "Project", "RP-019", ...
    "SampleID", "PUBLIC-REPORT-001", ...
    "Description", "", ...
    "Laboratory", "", ...
    "Tags", strings(0), ...
    "Comment", "");

spec = spectralab.core.Spectrum( ...
    wavelength, ...
    power, ...
    "RP-019 measurement", ...
    instrument, ...
    calibration, ...
    metadata, ...
    "relative");

spec = spec.withTimestamp(datetime(2026,7,30,9,30,0));

archive = spectralab.archive.create(spec);
spectralab.archive.save(archive, archiveFile);
end

function removeFolder(folder)

if isfolder(folder)
    rmdir(folder, "s");
end
end

function archive = createCriArchiveFile(archiveFile)

wavelength = (380:10:730).';
power = 0.2 + ...
    0.6 * exp(-0.5 * ((wavelength - 455) / 25).^2) + ...
    0.9 * exp(-0.5 * ((wavelength - 545) / 45).^2) + ...
    0.5 * exp(-0.5 * ((wavelength - 610) / 35).^2);

instrument = struct( ...
    "Name", "X-Rite i1Pro 2", ...
    "Driver", "spotread", ...
    "SerialNumber", "1001799");

metadata = struct( ...
    "Operator", "Christer Törnkvist", ...
    "Project", "RP-020", ...
    "SampleID", "CRI-PUBLIC-001");

spec = spectralab.core.Spectrum( ...
    wavelength, ...
    power, ...
    "CRI public report", ...
    instrument, ...
    struct(), ...
    metadata, ...
    "relative");

archive = spectralab.archive.create(spec);
spectralab.archive.save(archive, archiveFile);
end

function archive = createArchiveFileWithPower(archiveFile, power)

wavelength = (380:10:410).';

spec = spectralab.core.Spectrum( ...
    wavelength, ...
    power(:), ...
    "RP-020 two-archive measurement", ...
    struct("Name", "X-Rite i1Pro 2"), ...
    struct(), ...
    struct(), ...
    "relative");

archive = spectralab.archive.create(spec);
spectralab.archive.save(archive, archiveFile);
end
