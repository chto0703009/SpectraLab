function tests = test_report_generate
%TEST_REPORT_GENERATE Verify RP-019/RP-020 public report orchestration.

tests = functiontests(localfunctions);
end

function setup(testCase)

folder = string(tempname);
mkdir(folder);

testCase.TestData.TempFolder = folder;
testCase.addTeardown(@() removeFolder(folder));
end

function testRejectsUnknownAnalysisBeforeArchiveLoading(testCase)

verifyError(testCase, @() ...
    spectralab.report.generate( ...
        "missing.mat", ...
        "ANL-UNKNOWN", ...
        fullfile(testCase.TestData.TempFolder, "reports")), ...
    "SpectraLab:Report:UnknownAnalysisId");
end

function testRefusesToOverwriteExistingPdf(testCase)

folder = string(testCase.TestData.TempFolder);
archiveFile = fullfile(folder, "measurement.mat");
outputFolder = fullfile(folder, "reports");

createArchiveFile(archiveFile);

spectralab.report.generate( ...
    archiveFile, "ANL-SPECTRUM", outputFolder);

verifyError(testCase, @() ...
    spectralab.report.generate( ...
        archiveFile, "ANL-SPECTRUM", outputFolder), ...
    "SpectraLab:Report:ReportFileAlreadyExists");
end

function testGeneratesMeasuredSpectrumByAnalysisId(testCase)

folder = string(testCase.TestData.TempFolder);
archiveFile = fullfile(folder, "spectrum_measurement.mat");
outputFolder = fullfile(folder, "reports");

archive = createArchiveFile(archiveFile);

info = spectralab.report.generate( ...
    archiveFile, ...
    "ANL-SPECTRUM", ...
    outputFolder);

verifyTrue(testCase, isfile(info.PDFFile));
verifyTrue(testCase, isfile(info.PNGFile));
verifyEqual(testCase, ...
    info.Context.Analysis.AnalysisId, ...
    "ANL-SPECTRUM");
verifyEqual(testCase, info.AnalysisId, "ANL-SPECTRUM");
verifyEqual(testCase, ...
    info.Context.Result.SampleCount, ...
    numel(archive.Measurement.Wavelength));
verifyEqual(testCase, ...
    string(info.PDFFile), ...
    fullfile(outputFolder, ...
        "spectrum_measurement_ANL-SPECTRUM_report.pdf"));
verifyEqual(testCase, ...
    string(info.PNGFile), ...
    fullfile(outputFolder, ...
        "spectrum_measurement_ANL-SPECTRUM_figure.png"));
end

