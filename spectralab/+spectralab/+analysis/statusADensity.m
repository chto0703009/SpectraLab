function result = statusADensity(reference, sample, options)
%STATUSADENSITY Calculate Status A red, green, and blue densities.
%
%   RESULT = spectralab.analysis.statusADensity(REFERENCE, SAMPLE)
%
%   calculates Status A RGB densities using the common weighted-density
%   engine. The same calculation logic is used for all three channels;
%   only the spectral weighting function changes.
%
%   Name-value arguments
%   --------------------
%   Resample
%       Enable spectral pre-resampling before weighted integration.
%       Default: false.
%
%   RefinementFactor
%       Number of equal subintervals created within each original
%       wavelength interval. Default: 4.
%
%   InterpolationMethod
%       Interpolation method:
%
%           "pchip"   default
%           "makima"
%           "spline"

    arguments
        reference
        sample

        options.Resample (1,1) logical = false

        options.RefinementFactor (1,1) double ...
            {mustBeInteger, ...
             mustBeGreaterThanOrEqual(options.RefinementFactor, 1)} = 4

        options.InterpolationMethod (1,1) string ...
            {mustBeMember(options.InterpolationMethod, ...
                ["pchip", "makima", "spline"])} = "pchip"
    end

    redWeighting = spectralab.filters.statusA.red();
    greenWeighting = spectralab.filters.statusA.green();
    blueWeighting = spectralab.filters.statusA.blue();

    red = spectralab.core.weightedDensity( ...
        reference, ...
        sample, ...
        redWeighting, ...
        WeightingName="Status A Red", ...
        WarnAboveOne=false, ...
        Resample=options.Resample, ...
        RefinementFactor=options.RefinementFactor, ...
        InterpolationMethod=options.InterpolationMethod);

    green = spectralab.core.weightedDensity( ...
        reference, ...
        sample, ...
        greenWeighting, ...
        WeightingName="Status A Green", ...
        WarnAboveOne=false, ...
        Resample=options.Resample, ...
        RefinementFactor=options.RefinementFactor, ...
        InterpolationMethod=options.InterpolationMethod);

    blue = spectralab.core.weightedDensity( ...
        reference, ...
        sample, ...
        blueWeighting, ...
        WeightingName="Status A Blue", ...
        WarnAboveOne=false, ...
        Resample=options.Resample, ...
        RefinementFactor=options.RefinementFactor, ...
        InterpolationMethod=options.InterpolationMethod);

    densityRGB = [ ...
        red.Density, ...
        green.Density, ...
        blue.Density];

    transmittanceRGB = [ ...
        red.Transmittance, ...
        green.Transmittance, ...
        blue.Transmittance];

    if any(transmittanceRGB > 1)
        warning( ...
            "spectralab:analysis:statusADensity:TransmittanceAboveOne", ...
            "One or more Status A transmittance values exceed 1. " + ...
            "Check the reference measurement, sample measurement, " + ...
            "instrument stability, and measurement geometry.");
    end

    result = struct( ...
        "Red", red, ...
        "Green", green, ...
        "Blue", blue, ...
        "DensityRGB", densityRGB, ...
        "TransmittanceRGB", transmittanceRGB, ...
        "Standard", "Status A", ...
        "Resampled", options.Resample, ...
        "RefinementFactor", options.RefinementFactor, ...
        "InterpolationMethod", options.InterpolationMethod);

end