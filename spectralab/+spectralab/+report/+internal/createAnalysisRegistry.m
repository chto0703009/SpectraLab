function registry = createAnalysisRegistry()
%CREATEANALYSISREGISTRY Create the canonical RP-020 analysis registry.
%
%   registry = spectralab.report.internal.createAnalysisRegistry()
%
% RP-020 assigns canonical report specifications to public AnalysisId
% values. The registry is data-only and contains no mutable state.
%
% The first registered report type is ANL-SPECTRUM, representing direct
% reporting of the measured spectrum stored in one SpectraLab archive.

registry = [ ...
    makeEntry( ...
        "ANL-SPECTRUM", ...
        "Measured Spectrum", ...
        "Direct report of archived spectral measurement data", ...
        "Measurement", ...
        @runMeasuredSpectrum, ...
        @renderMeasuredSpectrum, ...
        @measuredSpectrumDefinition)
    makeEntry( ...
        "ANL-CRI", ...
        "Color Rendering Index", ...
        "CIE 13.3 color rendering analysis of archived spectral data", ...
        "Measurement", ...
        @runCri, ...
        @renderCriSpectrum, ...
        @criDefinition)
    makeEntry( ...
        "ANL-001", ...
        "Transmission", ...
        "Spectral transmission from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runTransmission, ...
        @renderTransmission, ...
        @transmissionDefinition)
    makeEntry( ...
        "ANL-002", ...
        "Optical Density", ...
        "Spectral optical density from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runOpticalDensity, ...
        @renderOpticalDensity, ...
        @opticalDensityDefinition)
    makeEntry( ...
        "ANL-004", ...
        "White Density", ...
        "Photopically weighted visual density from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runWhiteDensity, ...
        @noFigureRenderer, ...
        @whiteDensityDefinition)
    makeEntry( ...
        "ANL-005", ...
        "Status A Density", ...
        "Status A red, green, and blue densities from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runStatusADensity, ...
        @noFigureRenderer, ...
        @statusADensityDefinition)
    makeEntry( ...
        "ANL-008", ...
        "Status M Density", ...
        "Status M red, green, and blue densities from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runStatusMDensity, ...
        @noFigureRenderer, ...
        @statusMDensityDefinition)
    makeEntry( ...
        "ANL-007", ...
        "ISO Visual Density", ...
        "ISO visual transmission density from reference and sample archives", ...
        ["Reference", "Sample"], ...
        @runIsoVisualDensity, ...
        @noFigureRenderer, ...
        @isoVisualDensityDefinition)];

validateRegistry(registry);
end

function entry = makeEntry( ...
        analysisId, name, description, inputRoles, runner, ...
        figureRenderer, definitionFactory)

entry = struct( ...
    "AnalysisId", string(analysisId), ...
    "Name", string(name), ...
    "Description", string(description), ...
    "InputRoles", reshape(string(inputRoles), 1, []), ...
    "AnalysisRunner", runner, ...
    "FigureRenderer", figureRenderer, ...
    "DefinitionFactory", definitionFactory);
end

function validateRegistry(registry)
%VALIDATEREGISTRY Validate the canonical registry contract.

required = [ ...
    "AnalysisId"
    "Name"
    "Description"
    "InputRoles"
    "AnalysisRunner"
    "FigureRenderer"
    "DefinitionFactory"];

if ~isstruct(registry) || isempty(registry)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "Analysis registry must be a non-empty structure array.");
end

for fieldName = required.'
    if ~isfield(registry, fieldName)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Analysis registry is missing required field '%s'.", ...
            fieldName);
    end
end

analysisIds = [registry.AnalysisId];

if numel(unique(analysisIds)) ~= numel(analysisIds)
    error("SpectraLab:Report:DuplicateAnalysisId", ...
        "Analysis registry contains duplicate AnalysisId values.");
end

for k = 1:numel(registry)
    entry = registry(k);

    if ~isstring(entry.AnalysisId) || ...
            ~isscalar(entry.AnalysisId) || ...
            strlength(strtrim(entry.AnalysisId)) == 0
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Each registry AnalysisId must be a non-empty string scalar.");
    end

    if ~isstring(entry.InputRoles) || ...
            isempty(entry.InputRoles) || ...
            ~isrow(entry.InputRoles) || ...
            any(ismissing(entry.InputRoles)) || ...
            any(strlength(strtrim(entry.InputRoles)) == 0) || ...
            numel(unique(entry.InputRoles)) ~= numel(entry.InputRoles)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Each registry InputRoles value must be a unique non-empty string row vector.");
    end

    functionFields = [ ...
        "AnalysisRunner"
        "FigureRenderer"
        "DefinitionFactory"];

    for fieldName = functionFields.'
        if ~isa(entry.(fieldName), "function_handle")
            error("SpectraLab:Report:InvalidAnalysisRegistry", ...
                "Registry field '%s' must be a function handle.", ...
                fieldName);
        end
    end
end
end

function result = runMeasuredSpectrum(archive)
%RUNMEASUREDSPECTRUM Return report data for primary archived measurement.

result = struct( ...
    "SampleCount", numel(archive.Measurement.Wavelength), ...
    "WavelengthMinimum", min(archive.Measurement.Wavelength), ...
    "WavelengthMaximum", max(archive.Measurement.Wavelength));
end

function renderMeasuredSpectrum(ax, archive, ~)
%RENDERMEASUREDSPECTRUM Render the archived spectrum.

spec = spectralab.archive.restore(archive);

spectralab.plot.spectrum( ...
    spec, ...
    Parent=ax, ...
    Title="Measured spectral power distribution", ...
    Normalize=false, ...
    ShowSummary=false, ...
    ShowSpectralColorBar=true);
end

