function result = runOpticalDensity(referenceArchive, sampleArchive)
%RUNOPTICALDENSITY Run canonical spectral optical-density analysis.

transmissionAnalysis = spectralab.analysis.transmission( ...
    referenceArchive, ...
    sampleArchive, ...
    Resample=false, ...
    WarnAboveOne=false);

wavelength = transmissionAnalysis.Result.WavelengthNm(:);
transmission = transmissionAnalysis.Result.Value(:);
density = spectralab.analysis.opticalDensity(transmission);

result = struct( ...
    "SampleCount", numel(wavelength), ...
    "WavelengthMinimum", wavelength(1), ...
    "WavelengthMaximum", wavelength(end), ...
    "MeanDensity", mean(density), ...
    "WavelengthNm", wavelength, ...
    "Density", density, ...
    "TransmissionAnalysis", transmissionAnalysis);
end

function renderOpticalDensity(ax, ~, ~, result)
%RENDEROPTICALDENSITY Render the canonical optical-density spectrum.

spectralab.plot.opticalDensity( ...
    result.WavelengthNm, ...
    result.Density, ...
    Parent=ax, ...
    Title="Optical density spectrum", ...
    ShowGrid=true);
end

