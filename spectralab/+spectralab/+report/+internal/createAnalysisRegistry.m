function result = runSpectralMean(firstArchive, secondArchive, options)
%RUNSPECTRALMEAN Run canonical pointwise arithmetic mean.

arguments
    firstArchive
    secondArchive
    options.Resample (1,1) logical = false
    options.RefinementFactor (1,1) double = 1
    options.InterpolationMethod (1,1) string = "pchip"
    options.SourceFiles (1,:) string = ["", ""]
end

analysis = spectralab.analysis.spectralMean(firstArchive, secondArchive, ...
    Resample=options.Resample, ...
    RefinementFactor=options.RefinementFactor, ...
    InterpolationMethod=options.InterpolationMethod, ...
    SourceFiles=options.SourceFiles);
wavelength = analysis.Result.WavelengthNm;
value = analysis.Result.Value;
result = pairSpectrumResult(analysis, wavelength, value);
result.MeanValue = mean(value);
result.DerivedArchive = analysis.Result.DerivedArchive;
result.DerivedArchiveFile = "Not saved by report generation";
end

function renderSpectralMean(ax, firstArchive, secondArchive, result)
%RENDERSPECTRALMEAN Show both sources and their arithmetic mean.

plot(ax, firstArchive.Measurement.Wavelength, ...
    firstArchive.Measurement.Value, "--", "LineWidth", 1.0, ...
    "DisplayName", "Source A: " + result.SourceAFile);
hold(ax, "on");
plot(ax, secondArchive.Measurement.Wavelength, ...
    secondArchive.Measurement.Value, "--", "LineWidth", 1.0, ...
    "DisplayName", "Source B: " + result.SourceBFile);
plot(ax, result.WavelengthNm, result.Value, "k-", "LineWidth", 1.8, ...
    "DisplayName", "Mean of A and B");
grid(ax, "on");
xlabel(ax, "Wavelength (nm)");
ylabel(ax, "Spectral value (" + result.Unit + ")");
title(ax, "Spectral arithmetic mean");
maximumDisplayedValue = max([result.Value; ...
    firstArchive.Measurement.Value(:); secondArchive.Measurement.Value(:)]);
ylim(ax, [0, 1.05 * maximumDisplayedValue]);
spectralab.plot.spectralColorBar(ax);
legend(ax, "Location", "northeast", "Interpreter", "none");
end

