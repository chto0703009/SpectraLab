function registry = createAnalysisRegistry()
%CREATEANALYSISREGISTRY Create the canonical RP-020 analysis registry.
%
%   registry = spectralab.report.internal.createAnalysisRegistry()
%
% RP-020 assigns canonical report specifications to public AnalysisId
% values. The registry is data-only and contains no mutable state.
%
% The first registered report type is ANL-SPECTRUM, representing direct
% reporting of the measured spectrum stored in one SpectraLab archive.

registry = [ ...
    makeEntry( ...
        measuredSpectrumDefinition(), ...
        "Measurement", ...
        @runMeasuredSpectrum, ...
        @renderMeasuredSpectrum)
    makeEntry( ...
        criDefinition(), ...
        "Measurement", ...
        @runCri, ...
        @renderCriSpectrum)
    makeEntry( ...
        transmissionDefinition(), ...
        ["Reference", "Sample"], ...
        @runTransmission, ...
        @renderTransmission)
    makeEntry( ...
        opticalDensityDefinition(), ...
        ["Reference", "Sample"], ...
        @runOpticalDensity, ...
        @renderOpticalDensity)
    makeEntry( ...
        spectralMeanDefinition(), ...
        ["Source A", "Source B"], ...
        @runSpectralMean, ...
        @renderSpectralMean)
    makeEntry( ...
        spectralDifferenceDefinition(), ...
        ["Minuend (A)", "Subtrahend (B)"], ...
        @runSpectralDifference, ...
        @renderSpectralDifference)
    makeEntry( ...
        whiteDensityDefinition(), ...
        ["Reference", "Sample"], ...
        @runWhiteDensity, ...
        [])
    makeEntry( ...
        statusADensityDefinition(), ...
        ["Reference", "Sample"], ...
        @runStatusADensity, ...
        [])
    makeEntry( ...
        statusMDensityDefinition(), ...
        ["Reference", "Sample"], ...
        @runStatusMDensity, ...
        [])
    makeEntry( ...
        isoVisualDensityDefinition(), ...
        ["Reference", "Sample"], ...
        @runIsoVisualDensity, ...
        @renderIsoVisualDensity)];

validateRegistry(registry);
end

function entry = makeEntry( ...
        analysisDefinition, inputRoles, runner, figureRenderer)

entry = struct( ...
    "AnalysisDefinition", analysisDefinition, ...
    "InputRoles", reshape(string(inputRoles), 1, []), ...
    "AnalysisRunner", runner, ...
    "FigureRenderer", figureRenderer);
end

function validateRegistry(registry)
%VALIDATEREGISTRY Validate the canonical registry contract.

required = [ ...
    "AnalysisDefinition"
    "InputRoles"
    "AnalysisRunner"
    "FigureRenderer"];

if ~isstruct(registry) || isempty(registry)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "Analysis registry must be a non-empty structure array.");
end

for fieldName = required.'
    if ~isfield(registry, fieldName)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Analysis registry is missing required field '%s'.", ...
            fieldName);
    end
end

analysisIds = strings(1, numel(registry));

for k = 1:numel(registry)
    analysisIds(k) = registry(k).AnalysisDefinition.AnalysisId;
end

if numel(unique(analysisIds)) ~= numel(analysisIds)
    error("SpectraLab:Report:DuplicateAnalysisId", ...
        "Analysis registry contains duplicate AnalysisId values.");
end

for k = 1:numel(registry)
    entry = registry(k);

    validateDefinition(entry.AnalysisDefinition);

    if ~isstring(entry.InputRoles) || ...
            isempty(entry.InputRoles) || ...
            ~isrow(entry.InputRoles) || ...
            any(ismissing(entry.InputRoles)) || ...
            any(strlength(strtrim(entry.InputRoles)) == 0) || ...
            numel(unique(entry.InputRoles)) ~= numel(entry.InputRoles)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Each registry InputRoles value must be a unique non-empty string row vector.");
    end

    if ~isa(entry.AnalysisRunner, "function_handle")
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "Registry field 'AnalysisRunner' must be a function handle.");
    end

    if entry.AnalysisDefinition.HasFigure
        if ~isa(entry.FigureRenderer, "function_handle")
            error("SpectraLab:Report:InvalidAnalysisRegistry", ...
                "A figure-producing analysis requires a FigureRenderer.");
        end
    elseif ~isempty(entry.FigureRenderer)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "A figureless analysis must not define a FigureRenderer.");
    end
end
end

function validateDefinition(definition)
%VALIDATEDEFINITION Validate one authoritative analysis definition.

required = [ ...
    "AnalysisId"
    "Name"
    "Description"
    "Method"
    "Standard"
    "DefinitionVersion"
    "HasFigure"
    "ResultFields"];

if ~isstruct(definition) || ~isscalar(definition)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "Each AnalysisDefinition must be a scalar structure.");
end

for fieldName = required.'
    if ~isfield(definition, fieldName)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "AnalysisDefinition is missing required field '%s'.", ...
            fieldName);
    end
end

textFields = [ ...
    "AnalysisId"
    "Name"
    "Description"
    "Method"
    "Standard"
    "DefinitionVersion"];

for fieldName = textFields.'
    value = definition.(fieldName);
    if ~isstring(value) || ~isscalar(value) || ...
            ismissing(value) || strlength(strtrim(value)) == 0
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "AnalysisDefinition.%s must be non-empty scalar text.", ...
            fieldName);
    end
end

if ~islogical(definition.HasFigure) || ~isscalar(definition.HasFigure)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "AnalysisDefinition.HasFigure must be a logical scalar.");
end

if ~isstruct(definition.ResultFields) || isempty(definition.ResultFields)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "AnalysisDefinition.ResultFields must be a non-empty structure array.");
end

requiredResultFields = ["Field", "Label", "Unit", "Format"];
for fieldName = requiredResultFields
    if ~isfield(definition.ResultFields, fieldName)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "AnalysisDefinition.ResultFields is missing field '%s'.", ...
            fieldName);
    end
end

for k = 1:numel(definition.ResultFields)
    resultFieldDefinition = definition.ResultFields(k);

    nonEmptyFields = ["Field", "Label", "Format"];
    for fieldName = nonEmptyFields
        value = resultFieldDefinition.(fieldName);
        if ~isstring(value) || ~isscalar(value) || ...
                ismissing(value) || strlength(strtrim(value)) == 0
            error("SpectraLab:Report:InvalidAnalysisRegistry", ...
                "ResultFields.%s must be non-empty scalar text.", ...
                fieldName);
        end
    end

    if ~isstring(resultFieldDefinition.Unit) || ...
            ~isscalar(resultFieldDefinition.Unit) || ...
            ismissing(resultFieldDefinition.Unit)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "ResultFields.Unit must be scalar text.");
    end
end

resultFieldNames = [definition.ResultFields.Field];
if numel(unique(resultFieldNames)) ~= numel(resultFieldNames)
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "AnalysisDefinition.ResultFields contains duplicate Field values.");
end

hasFigureDefinition = isfield(definition, "FigureDefinition");
if definition.HasFigure ~= hasFigureDefinition
    error("SpectraLab:Report:InvalidAnalysisRegistry", ...
        "HasFigure and FigureDefinition must describe the same figure contract.");
end

if definition.HasFigure
    figureDefinition = definition.FigureDefinition;
    requiredFigureFields = [ ...
        "AspectRatio"
        "WidthFraction"
        "MaxHeight"
        "Caption"];

    if ~isstruct(figureDefinition) || ~isscalar(figureDefinition)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "FigureDefinition must be a scalar structure.");
    end

    for fieldName = requiredFigureFields.'
        if ~isfield(figureDefinition, fieldName)
            error("SpectraLab:Report:InvalidAnalysisRegistry", ...
                "FigureDefinition is missing field '%s'.", fieldName);
        end
    end

    numericValues = [ ...
        figureDefinition.AspectRatio
        figureDefinition.WidthFraction
        figureDefinition.MaxHeight];

    if ~isnumeric(numericValues) || ...
            any(~isfinite(numericValues)) || any(numericValues <= 0)
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "FigureDefinition dimensions must be positive finite numbers.");
    end

    if ~isstring(figureDefinition.Caption) || ...
            ~isscalar(figureDefinition.Caption) || ...
            ismissing(figureDefinition.Caption) || ...
            strlength(strtrim(figureDefinition.Caption)) == 0
        error("SpectraLab:Report:InvalidAnalysisRegistry", ...
            "FigureDefinition.Caption must be non-empty scalar text.");
    end
end
end

