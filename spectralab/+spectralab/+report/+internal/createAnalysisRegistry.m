function result = pairSpectrumResult(analysis, wavelength, value)
sources = analysis.Sources;
result = struct( ...
    "SourceAFile", sourceDisplayName(sources(1)), ...
    "SourceBFile", sourceDisplayName(sources(2)), ...
    "SourceAUUID", sources(1).UUID, ...
    "SourceBUUID", sources(2).UUID, ...
    "SourceAContentHash", sources(1).ContentHash, ...
    "SourceBContentHash", sources(2).ContentHash, ...
    "SampleCount", numel(wavelength), ...
    "WavelengthMinimum", wavelength(1), ...
    "WavelengthMaximum", wavelength(end), ...
    "WavelengthNm", wavelength(:), ...
    "Value", value(:), ...
    "Unit", analysis.Result.Unit, ...
    "Analysis", analysis);
end

function value = sourceDisplayName(source)
value = source.Filename;
if strlength(value) == 0
    value = source.MeasurementName;
end
end

