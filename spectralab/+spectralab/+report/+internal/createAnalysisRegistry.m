function renderSpectralDifference(ax, ~, ~, result)
%RENDERSPECTRALDIFFERENCE Render signed difference with a zero baseline.

plot(ax, result.WavelengthNm, result.Value, ...
    "Color", [0.85 0.15 0.15], "LineWidth", 1.6, ...
    "DisplayName", result.SourceAFile + " - " + result.SourceBFile);
grid(ax, "on");
xlabel(ax, "Wavelength (nm)");
ylabel(ax, "Signed difference (" + result.Unit + ")");
title(ax, "Spectral difference: A - B");
maximumAbsoluteDifference = max(abs(result.Value));
if maximumAbsoluteDifference == 0
    maximumAbsoluteDifference = 1;
end
yMargin = 0.05 * maximumAbsoluteDifference;
yExtent = maximumAbsoluteDifference + yMargin;
ylim(ax, [-yExtent, yExtent]);
ax.XAxisLocation = "origin";
spectralab.plot.spectralColorBar(ax);
legend(ax, "Location", "northeast", "Interpreter", "none");
end

