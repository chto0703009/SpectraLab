function info = exportPDF(pdfFile, layoutPlan, renderContext)
%EXPORTPDF Export a minimal self-contained A4 portrait PDF.
%
%   info = spectralab.report.internal.exportPDF( ...
%       pdfFile, layoutPlan, renderContext)
%
% RP-017a renders heading, paragraph, tables, spacer, captions, and the
% actual report-owned figure. It reads the completed LayoutPlan and
% RenderContext only; it performs no analysis or layout calculations.

arguments
    pdfFile (1,1) string
    layoutPlan (:,1) struct
    renderContext (1,1) struct
end

pdfFile = validateTarget(pdfFile);
validateInputs(layoutPlan, renderContext);

folder = string(fileparts(pdfFile));
if folder == ""
    folder = string(pwd);
end

temporaryFile = string(tempname(folder)) + ".pdf";
cleanupTemporary = onCleanup(@() deleteIfExists(temporaryFile)); %#ok<NASGU>

pageCount = max([layoutPlan.Page], [], "omitmissing");
if isempty(pageCount) || pageCount < 1
    pageCount = 1;
end

layout = spectralab.report.internal.createLayoutState();
records = renderContext.State.RenderedElements;

for page = 1:pageCount
    fig = createPageFigure(layout);
    cleanupFigure = onCleanup(@() closeIfValid(fig)); %#ok<NASGU>

    drawPageFrame( ...
        fig, ...
        layout, ...
        renderContext.PageFrame, ...
        page, ...
        pageCount);

    pagePlacements = layoutPlan([layoutPlan.Page] == page);
    for k = 1:numel(pagePlacements)
        placement = pagePlacements(k);
        if placement.ExplicitPageBreak
            continue
        end
        if ~placement.Measured
            error("SpectraLab:Report:UnmeasuredPDFElement", ...
                "PDF export requires a measured element. Element '%s' has no layout height.", ...
                placement.ElementId);
        end

        record = findRecord(records, placement.ElementId);
        drawElement(fig, layout, placement, record, renderContext);
    end

    if page == 1
        exportgraphics(fig, temporaryFile, ...
            "ContentType", "vector", ...
            "BackgroundColor", "white");
    else
        exportgraphics(fig, temporaryFile, ...
            "ContentType", "vector", ...
            "BackgroundColor", "white", ...
            "Append", true);
    end

    closeIfValid(fig);
    clear cleanupFigure
end

[ok, message] = movefile(temporaryFile, pdfFile);
if ~ok
    error("SpectraLab:Report:PDFExportFailed", ...
        "Unable to finalize PDF report '%s': %s", pdfFile, message);
end

info = struct( ...
    "PDFFile", pdfFile, ...
    "PageCount", double(pageCount), ...
    "Format", "PDF", ...
    "PageSize", "A4", ...
    "Orientation", "portrait");
end

function pdfFile = validateTarget(pdfFile)
pdfFile = string(pdfFile);
if ~endsWith(lower(pdfFile), ".pdf")
    error("SpectraLab:Report:InvalidPDFFile", ...
        "PDF output filename must use the .pdf extension.");
end

folder = string(fileparts(pdfFile));
if folder ~= "" && ~isfolder(folder)
    error("SpectraLab:Report:OutputFolderNotFound", ...
        "PDF output folder does not exist: %s", folder);
end

if isfile(pdfFile)
    error("SpectraLab:Report:ReportFileAlreadyExists", ...
        "Report file already exists: %s", pdfFile);
end
end

function validateInputs(layoutPlan, renderContext)
requiredPlacement = ["ElementId", "ElementType", "Page", "Y", ...
    "Height", "Measured", "ExplicitPageBreak", "AutomaticPageBreak"];
for k = 1:numel(layoutPlan)
    for j = 1:numel(requiredPlacement)
        if ~isfield(layoutPlan(k), requiredPlacement(j))
            error("SpectraLab:Report:InvalidLayoutPlan", ...
                "LayoutPlan entry is missing required field '%s'.", ...
                requiredPlacement(j));
        end
    end
end

if ~isfield(renderContext, "State") || ...
        ~isfield(renderContext.State, "RenderedElements") || ...
        ~isstruct(renderContext.State.RenderedElements)
    error("SpectraLab:Report:InvalidRenderContext", ...
        "RenderContext must contain State.RenderedElements.");
end

if ~isfield(renderContext, "PageFrame") || ...
        ~isstruct(renderContext.PageFrame) || ...
        ~isscalar(renderContext.PageFrame)
    error("SpectraLab:Report:InvalidPageFrame", ...
        "RenderContext must contain one PageFrame model.");
end
end

function fig = createPageFigure(layout)
style = spectralab.report.internal.createReportStyle();
fig = figure( ...
    "Visible", "off", ...
    "Color", style.Appearance.BackgroundColor, ...
    "Units", "points", ...
    "Position", [100 100 layout.PageWidth layout.PageHeight], ...
    "PaperUnits", "points", ...
    "PaperSize", [layout.PageWidth layout.PageHeight], ...
    "PaperPosition", [0 0 layout.PageWidth layout.PageHeight], ...
    "InvertHardcopy", "off", ...
    "MenuBar", "none", ...
    "ToolBar", "none");

% A full-page background axes prevents exportgraphics from tightly cropping
% the document to its annotations. This preserves the physical A4 canvas and
% therefore the declared 20 mm page margins.
bg = axes(fig, ...
    "Units", "normalized", ...
    "Position", [0 0 1 1], ...
    "XLim", [0 1], ...
    "YLim", [0 1], ...
    "Color", style.Appearance.BackgroundColor, ...
    "Visible", "off", ...
    "HitTest", "off", ...
    "HandleVisibility", "off");
rectangle(bg, "Position", [0 0 1 1], ...
    "FaceColor", "white", ...
    "EdgeColor", "none", ...
    "HitTest", "off", ...
    "HandleVisibility", "off");
end

function drawPageFrame(fig, layout, model, page, pageCount)
style = spectralab.report.internal.createReportStyle();
%DRAWPAGEFRAME Draw the fixed report header and footer.

validatePageFrame(model);

left = layout.MarginLeft / layout.PageWidth;
right = 1 - layout.MarginRight / layout.PageWidth;
contentWidth = right - left;

headerY = 1 - 34 / layout.PageHeight;
footerY = 20 / layout.PageHeight;

headerHeight = 16 / layout.PageHeight;
footerHeight = 16 / layout.PageHeight;

headerLeft = [left headerY contentWidth/2 headerHeight];
headerRight = [left + contentWidth/2 headerY contentWidth/2 headerHeight];

footerLeft = [left footerY contentWidth/3 footerHeight];
footerCenter = [left + contentWidth/3 footerY contentWidth/3 footerHeight];
footerRight = [left + 2*contentWidth/3 footerY contentWidth/3 footerHeight];

drawPageFrameHeaderText( ...
    fig, headerLeft, headerRight, model, style);

drawPageFrameText(fig, footerLeft, model.FooterLeft, ...
    "left", style.PageFrame.FooterFontSize, ...
    style.Font.WeightNormal, "normal", "middle", style);
drawPageFrameText(fig, footerCenter, model.FooterCenter, ...
    "center", style.PageFrame.FooterFontSize, ...
    style.Font.WeightNormal, "normal", "middle", style);
drawPageFrameText(fig, footerRight, ...
    "Page " + string(page) + " of " + string(pageCount), ...
    "right", style.PageFrame.FooterFontSize, ...
    style.Font.WeightNormal, "normal", "middle", style);

headerRuleY = 1 - layout.MarginTop / layout.PageHeight + ...
    style.PageFrame.RuleOffset / layout.PageHeight;
footerRuleY = layout.MarginBottom / layout.PageHeight - ...
    style.PageFrame.RuleOffset / layout.PageHeight;

annotation(fig, "line", [left right], [headerRuleY headerRuleY], ...
    "Color", style.Appearance.PageFrameRuleColor, ...
    "LineWidth", style.Appearance.PageFrameRuleLineWidth);

annotation(fig, "line", [left right], [footerRuleY footerRuleY], ...
    "Color", style.Appearance.PageFrameRuleColor, ...
    "LineWidth", style.Appearance.PageFrameRuleLineWidth);
end


function drawPageFrameHeaderText( ...
        fig, leftPosition, rightPosition, model, style)
%DRAWPAGEFRAMEHEADERTEXT Draw both header texts in one shared row.

headerAxes = axes( ...
    "Parent", fig, ...
    "Units", "normalized", ...
    "Position", [0 0 1 1], ...
    "Visible", "off", ...
    "XLim", [0 1], ...
    "YLim", [0 1], ...
    "HitTest", "off");

rowCenterY = leftPosition(2) + leftPosition(4) / 2;

text(headerAxes, ...
    leftPosition(1), ...
    rowCenterY, ...
    char(string(model.HeaderLeft)), ...
    "Interpreter", "none", ...
    "FontName", style.Font.Name, ...
    "FontSize", style.PageFrame.HeaderTitleFontSize, ...
    "FontWeight", style.Font.WeightBold, ...
    "FontAngle", style.Font.AngleItalic, ...
    "HorizontalAlignment", "left", ...
    "VerticalAlignment", "middle", ...
    "Clipping", "off");

text(headerAxes, ...
    rightPosition(1) + rightPosition(3), ...
    rowCenterY, ...
    char(string(model.HeaderRight)), ...
    "Interpreter", "none", ...
    "FontName", style.Font.Name, ...
    "FontSize", style.PageFrame.HeaderInformationFontSize, ...
    "FontWeight", style.Font.WeightNormal, ...
    "FontAngle", "normal", ...
    "HorizontalAlignment", "right", ...
    "VerticalAlignment", "middle", ...
    "Clipping", "off");
end


