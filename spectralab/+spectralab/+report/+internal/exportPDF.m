    "FontName", style.Font.Name, ...
    "FontSize", fontSize, ...
    "FontWeight", fontWeight, ...
    "FontAngle", fontAngle, ...
    "HorizontalAlignment", alignment, ...
    "VerticalAlignment", verticalAlignment, ...
    "EdgeColor", "none", ...
    "Margin", style.PageFrame.TextMargin, ...
    "FitBoxToText", "off");
end


function validatePageFrame(model)

required = [ ...
    "Format"
    "Version"
    "HeaderLeft"
    "HeaderRight"
    "FooterLeft"
    "FooterCenter"];

for fieldName = required.'
    if ~isfield(model, fieldName)
        error("SpectraLab:Report:InvalidPageFrame", ...
            "PageFrame is missing required field '%s'.", ...
            fieldName);
    end
end

if string(model.Format) ~= "SLAB-REPORT-PAGE-FRAME"
    error("SpectraLab:Report:InvalidPageFrame", ...
        "PageFrame has an unsupported format.");
end
end


function record = findRecord(records, elementId)
matches = string({records.Id}) == string(elementId);
if nnz(matches) ~= 1
    error("SpectraLab:Report:MissingRenderedElement", ...
        "Expected exactly one rendered element for '%s'.", elementId);
end
record = records(matches);
end

function drawElement(fig, layout, placement, record, renderContext)
style = spectralab.report.internal.createReportStyle();
type = string(record.Type);
switch type
    case "heading"
        drawTextBox(fig, layout, placement, string(record.Content), ...
            style.Text.HeadingFontSize, "bold", "left", style);
    case "paragraph"
        drawTextBox(fig, layout, placement, string(record.Content), ...
            style.Text.ParagraphFontSize, "normal", "left", style);
    case "table"
        if string(record.Role) == "informationBox"
            drawInformationBox(fig, layout, placement, record.Content);
        else
            drawResultsTable(fig, layout, placement, record.Content);
        end
    case "figure"
        drawReportFigure(fig, layout, placement, record.Content, renderContext);
    case "caption"
        drawFigureCaption(fig, layout, placement, record.Content);
    case "spacer"
        % A spacer consumes layout height but draws no marks.
    otherwise
        error("SpectraLab:Report:UnsupportedPDFElement", ...
            "RP-012 PDF backend does not support element type '%s'.", type);
end
end

function drawTextBox(fig, layout, placement, content, fontSize, fontWeight, alignment, style)
pos = normalizedBox(layout, placement, layout.ContentWidth);
annotation(fig, "textbox", pos, ...
    "String", char(content), ...
    "Interpreter", "none", ...
    "FontName", style.Font.Name, ...
    "FontSize", fontSize, ...
    "FontWeight", fontWeight, ...
    "HorizontalAlignment", alignment, ...
    "VerticalAlignment", "top", ...
    "EdgeColor", "none", ...
    "Margin", style.Text.Margin, ...
    "FitBoxToText", "off");
end

function [innerPlacement, titleHeight] = drawBoxTitle( ...
        fig, layout, boxPlacement, boxWidth, model)

style = spectralab.report.internal.createReportStyle();

titleHeight = 0;
innerPlacement = boxPlacement;

if ~isfield(model, "Title") || ...
        strlength(strtrim(string(model.Title))) == 0
    return
end

titleHeight = style.Box.TitleHeight;
titlePlacement = boxPlacement;
titlePlacement.Height = titleHeight;

titlePosition = normalizedBox( ...
    layout, ...
    titlePlacement, ...
    boxWidth);

annotation(fig, "textbox", titlePosition, ...
    "String", char(string(model.Title)), ...
    "Interpreter", "none", ...
    "FontName", style.Font.Name, ...
    "FontSize", style.Box.TitleFontSize, ...
    "FontWeight", style.Font.WeightBold, ...
    "HorizontalAlignment", "left", ...
    "VerticalAlignment", "middle", ...
    "EdgeColor", "none", ...
    "Margin", style.Box.TitleMargin, ...
    "FitBoxToText", "off");

innerPlacement.Y = innerPlacement.Y + titleHeight;
innerPlacement.Height = max(innerPlacement.Height - titleHeight, 1);
end


function drawResultsTable(fig, layout, placement, model)
%DRAWRESULTSTABLE Draw a compact framed report table.
%
% The table uses 62 percent of the available content width and is aligned
% to the left margin. The remaining area on the right is intentionally
% left blank for handwritten notes.
%
% The table is inset vertically within its measured layout area to create
% visible separation from adjacent report elements.

style = spectralab.report.internal.createReportStyle();

    if ~isstruct(model) || ~isfield(model, "Rows")
        error("SpectraLab:Report:InvalidPDFTable", ...
            "PDF table element does not contain a valid table model.");
    end

    rows = model.Rows;
    rowCount = numel(rows);

    if rowCount == 0
        return
    end

    rowLineCounts = arrayfun(@resultsTableRowLineCount, rows);
    totalLineCount = sum(rowLineCounts);

    boxWidthFraction = style.Box.WidthFraction;

    if isfield(model, "Role") && string(model.Role) == "provenance"
        boxWidthFraction = ...
            style.ResultsTable.ProvenanceWidthFraction;
    end

    boxWidth = layout.ContentWidth * boxWidthFraction;
    verticalGap = style.ResultsTable.VerticalGap;

    boxPlacement = placement;
    boxPlacement.Y = placement.Y + verticalGap / 2;
    boxPlacement.Height = max(placement.Height - verticalGap, 1);

    boxPosition = normalizedBox( ...
        layout, ...
        boxPlacement, ...
        boxWidth);

    annotation(fig, "rectangle", boxPosition, ...
        "LineWidth", style.Appearance.BoxBorderLineWidth, ...
        "EdgeColor", style.Appearance.BoxBorderColor);

    [innerPlacement, ~] = drawBoxTitle( ...
        fig, layout, boxPlacement, boxWidth, model);

    padding = style.Box.ContentPadding;
    innerPlacement.Y = innerPlacement.Y + padding;
    innerPlacement.Height = max( ...
        innerPlacement.Height - 2 * padding, ...
        1);

    lineHeight = innerPlacement.Height / totalLineCount;

    labelWidth = boxWidth * style.ResultsTable.LabelWidthFraction;
    valueWidth = boxWidth - labelWidth;

    lineOffset = 0;

    for k = 1:rowCount
        rowPlacement = innerPlacement;
        rowPlacement.Y = ...
            innerPlacement.Y + lineOffset * lineHeight;
        rowPlacement.Height = rowLineCounts(k) * lineHeight;

        lineOffset = lineOffset + rowLineCounts(k);

        labelPosition = normalizedBox( ...
            layout, ...
            rowPlacement, ...
            labelWidth);

        valuePosition = normalizedBox( ...
            layout, ...
            rowPlacement, ...
            valueWidth);

        valuePosition(1) = valuePosition(1) + ...
            labelWidth / layout.PageWidth;

        annotation(fig, "textbox", labelPosition, ...
            "String", char(string(rows(k).Label)), ...
            "Interpreter", "none", ...
            "FontName", style.Font.Name, ...
            "FontSize", style.ResultsTable.FontSize, ...
            "FontWeight", style.Font.WeightBold, ...
            "HorizontalAlignment", "left", ...
            "VerticalAlignment", "middle", ...
            "EdgeColor", "none", ...
            "Margin", style.Box.CellMargin, ...
            "FitBoxToText", "off");

        annotation(fig, "textbox", valuePosition, ...
            "String", char(string(rows(k).DisplayText)), ...
            "Interpreter", "none", ...
            "FontName", style.Font.Name, ...
            "FontSize", style.ResultsTable.FontSize, ...
            "FontWeight", style.Font.WeightNormal, ...
            "HorizontalAlignment", "left", ...
            "VerticalAlignment", "middle", ...
            "EdgeColor", "none", ...
            "Margin", style.Box.CellMargin, ...
            "FitBoxToText", "off");
    end
end


function count = resultsTableRowLineCount(row)

count = 1;

if isfield(row, "LineCount")
    candidate = double(row.LineCount);

    if isscalar(candidate) && isfinite(candidate) && candidate >= 1
        count = candidate;
    end
end
end


function drawInformationBox(fig, layout, placement, model)
%DRAWINFORMATIONBOX Draw a compact framed information box.
%
% The box uses 62 percent of the available content width and is aligned to
% the left page margin. The remaining width on the right is intentionally
% left blank for handwritten notes on printed reports.

style = spectralab.report.internal.createReportStyle();

if ~isstruct(model) || ...
        ~isfield(model, "MeasurementInformationRows") || ...
        ~isfield(model, "ResultRows")

    error("SpectraLab:Report:InvalidInformationBox", ...
        "PDF InformationBox element has an invalid model.");
end

rows = [ ...
    model.MeasurementInformationRows
    metadataFromResults(model.ResultRows)];

if isempty(rows)
    return
end

boxWidth = layout.ContentWidth * style.Box.WidthFraction;
verticalGap = style.InformationBox.VerticalGap;

boxPlacement = placement;
boxPlacement.Y = placement.Y + verticalGap / 2;
boxPlacement.Height = max(placement.Height - verticalGap, 1);

boxPosition = normalizedBox(layout, boxPlacement, boxWidth);

annotation(fig, "rectangle", boxPosition, ...
    "LineWidth", style.Appearance.BoxBorderLineWidth, ...
    "EdgeColor", style.Appearance.BoxBorderColor);

[innerPlacement, ~] = drawBoxTitle( ...
    fig, layout, boxPlacement, boxWidth, model);

padding = style.Box.ContentPadding;
innerPlacement.Y = innerPlacement.Y + padding;
innerPlacement.Height = max( ...
    innerPlacement.Height - 2 * padding, ...
    1);

rowHeight = innerPlacement.Height / numel(rows);

labelWidth = boxWidth * style.InformationBox.LabelWidthFraction;
valueWidth = boxWidth - labelWidth;

for k = 1:numel(rows)
    rowPlacement = innerPlacement;
    rowPlacement.Y = ...
        innerPlacement.Y + (k - 1) * rowHeight;
    rowPlacement.Height = rowHeight;

    labelPosition = normalizedBox( ...
        layout, ...
        rowPlacement, ...
        labelWidth);

    valuePosition = normalizedBox( ...
        layout, ...
        rowPlacement, ...
        valueWidth);

    valuePosition(1) = valuePosition(1) + ...
        labelWidth / layout.PageWidth;

    annotation(fig, "textbox", labelPosition, ...
        "String", char(string(rows(k).Label)), ...
        "Interpreter", "none", ...
        "FontName", style.Font.Name, ...
        "FontSize", style.InformationBox.FontSize, ...
        "FontWeight", style.Font.WeightBold, ...
        "HorizontalAlignment", "left", ...
        "VerticalAlignment", "middle", ...
        "EdgeColor", "none", ...
        "Margin", style.Box.CellMargin, ...
        "FitBoxToText", "off");

    annotation(fig, "textbox", valuePosition, ...
        "String", char(string(rows(k).DisplayText)), ...
        "Interpreter", "none", ...
        "FontName", style.Font.Name, ...
        "FontSize", style.InformationBox.FontSize, ...
        "FontWeight", style.Font.WeightNormal, ...
        "HorizontalAlignment", "left", ...
        "VerticalAlignment", "middle", ...
        "EdgeColor", "none", ...
        "Margin", style.Box.CellMargin, ...
        "FitBoxToText", "off");
end
end


function rows = metadataFromResults(resultRows)
rows = repmat(struct("Label","","DisplayText",""),numel(resultRows),1);
for k=1:numel(resultRows)
    rows(k).Label = string(resultRows(k).Label);
    rows(k).DisplayText = string(resultRows(k).DisplayText);
end
end

function drawFigureCaption(fig, layout, placement, model)
style = spectralab.report.internal.createReportStyle();
if ~isstruct(model) || ~isfield(model, "Text") || ...
        string(model.Role) ~= "primaryFigureCaption"
    error("SpectraLab:Report:InvalidFigureCaption", ...
        "PDF caption element does not contain a valid figure-caption model.");
