function artifact = createSpectralArtifact(sessionFile, options)
%CREATESPECTRALARTIFACT Bundle a complete ColorChecker session in one file.
arguments
    sessionFile (1,1) string
    options.WavelengthRangeNm (1,2) double = [400 730]
end
range=options.WavelengthRangeNm;
if any(~isfinite(range)) || range(1)>=range(2)
    error("SpectraLab:ColorChecker:InvalidWavelengthRange", ...
        "WavelengthRangeNm must contain two increasing finite values.");
end
session = spectralab.colorchecker.load(sessionFile);
if any(string({session.Patches.State}) ~= "measured")
    error("SpectraLab:ColorChecker:SessionIncomplete", ...
        "A ColorChecker spectral artifact requires all patches to be measured.");
end
count = numel(session.Patches);
patchIDs = strings(count,1); sources = repmat(struct( ...
    "UUID","","ContentHash","","ArchiveFile",""),count,1);
wavelength = []; values = [];
for index = 1:count
    patch = session.Patches(index);
    archiveFile = string(patch.ArchiveFile);
    if ~isfile(archiveFile)
        archiveFile = fullfile(string(session.Context.SessionFolder),archiveFile);
    end
    archive = spectralab.archive.load(archiveFile,Quiet=true,Validation="error");
    if string(archive.Identity.UUID) ~= string(patch.ArchiveUUID) || ...
            string(archive.Identity.ContentHash) ~= string(patch.ArchiveContentHash)
        error("SpectraLab:ColorChecker:PatchArchiveIdentityMismatch", ...
            "Patch %s does not match its recorded source archive.",patch.Coordinate);
    end
    if index == 1
        wavelength = double(archive.Measurement.Wavelength(:));
        values = zeros(numel(wavelength),count);
    elseif ~isequal(wavelength,double(archive.Measurement.Wavelength(:)))
        error("SpectraLab:ColorChecker:WavelengthMismatch", ...
            "ColorChecker patch spectra must use one common wavelength grid.");
    end
    patchIDs(index) = string(patch.Coordinate);
    values(:,index) = double(archive.Measurement.Value(:));
    sources(index) = struct("UUID",string(archive.Identity.UUID), ...
        "ContentHash",string(archive.Identity.ContentHash), ...
        "ArchiveFile",string(patch.ArchiveFile));
end
keep=wavelength>=range(1) & wavelength<=range(2);
if nnz(keep)<2
    error("SpectraLab:ColorChecker:InsufficientCamera41Samples", ...
        "Fewer than two patch samples lie within %.1f-%.1f nm.", ...
        range(1),range(2));
end
wavelength=wavelength(keep);
values=values(keep,:);
effectiveRange=[wavelength(1) wavelength(end)];
payload = struct("Target",session.Definition, ...
    "PatchIDs",patchIDs,"WavelengthNm",wavelength, ...
    "Values",values,"Unit","1", ...
    "RequestedWavelengthRangeNm",range, ...
    "EffectiveWavelengthRangeNm",effectiveRange);
if isfield(session,"ColorimetryConversions") && ...
        ~isempty(session.ColorimetryConversions)
    payload.Colorimetry = session.ColorimetryConversions(end);
end
artifact = struct("Schema","spectralab.spectral-artifact", ...
    "SchemaVersion","1.0","Identity",struct(),"Origin","derived", ...
    "Kind","spectrum_set","Quantity","spectral_reflectance", ...
    "Payload",payload,"Provenance",struct( ...
        "SourceSessionFile",sessionFile, ...
        "SourceSessionUUID",string(session.Identity.UUID), ...
        "Sources",sources, ...
        "RequestedOutputWavelengthRangeNm",range, ...
        "EffectiveOutputWavelengthRangeNm",effectiveRange, ...
        "Output",struct("Type","SpectrumSet", ...
            "Cardinality",count,"Role","ReusableAnalysisInput")));
artifact.Identity = struct("UUID",string(java.util.UUID.randomUUID), ...
    "Created",datetime("now","TimeZone","UTC"), ...
    "ContentHash",spectralab.archive.contentHash(rmfield(artifact,"Identity")));
end
